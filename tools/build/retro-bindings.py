#!/usr/bin/env python3
"""Generate guarded libretro entry tables; no system hand-writes wrappers."""
from pathlib import Path
import re, sys
# (return type, entry, arguments, call, safe failure)
ENTRIES = [
 ('void','set_environment','retro_environment_t cb','cb',''),
 ('void','set_video_refresh','retro_video_refresh_t cb','cb',''),
 ('void','set_audio_sample','retro_audio_sample_t cb','cb',''),
 ('void','set_audio_sample_batch','retro_audio_sample_batch_t cb','cb',''),
 ('void','set_input_poll','retro_input_poll_t cb','cb',''),
 ('void','set_input_state','retro_input_state_t cb','cb',''),
 ('void','cheat_reset','void','',''),
 ('void','cheat_set','unsigned i,bool enabled,const char *code','i,enabled,code',''),
 *[('void',n,'void','','') for n in ('init','deinit','run','reset','unload_game')],
 ('bool','load_game','const struct retro_game_info *g','g','false'),
 ('void','get_system_info','struct retro_system_info *p','p',''),
 ('void','get_system_av_info','struct retro_system_av_info *p','p',''),
 ('void *','get_memory_data','unsigned id','id','NULL'),
 ('size_t','get_memory_size','unsigned id','id','0'),
 ('size_t','serialize_size','void','','0'),
 ('bool','serialize','void *p,size_t n','p,n','false'),
 ('bool','unserialize','const void *p,size_t n','p,n','false'),
]
def generate(system,prefix,omit=()):
 if not re.fullmatch(r'[a-z][a-z0-9]{1,7}',system) or (prefix and not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*',prefix)):
  raise ValueError('invalid id or prefix')
 lines=['/* Generated by retro-bindings.py. */','#include "retro_host.h"','#include "bb_arena.h"',f'extern const bb_system_t bb_system_{system};',
 'static bool held(void) {return bb_exec_held() && bb_session_system()==&bb_system_'+system+';}']
 for ret,name,args,call,fail in ENTRIES:
  if name in omit:continue
  real=prefix+'retro_'+name
  lines += [f'extern {ret} {real}({args});',f'static {ret} guarded_{name}({args}) {{']
  if ret=='void':lines += [f' if(held()) {real}({call});']
  else:lines += [f' return held()?{real}({call}):{fail};']
  lines+=['}']
 lines += [f'extern void (*__bb_{system}_init_start[])(void), (*__bb_{system}_init_end[])(void);',
           f'extern void (*__bb_{system}_fini_start[])(void), (*__bb_{system}_fini_end[])(void);',
           f'static bool activate(void) {{if(!held())return false;for(void (**p)(void)=__bb_{system}_init_start;p<__bb_{system}_init_end;p++)(*p)();return true;}}',
           f'static void deactivate(void) {{if(held())for(void (**p)(void)=__bb_{system}_fini_end;p>__bb_{system}_fini_start;)(*--p)();}}',
           f'const bb_retro_core bb_retro_{system}={{.activate=activate,.deactivate=deactivate,']
 lines += [f' .{name}=guarded_{name},' for ret,name,args,call,fail in ENTRIES if name not in omit]
 return '\n'.join(lines+['};',''])
if __name__=='__main__':
 system,prefix,out,*omitted=sys.argv[1:];p=Path(out);text=generate(system,prefix,omitted[0].split() if omitted else ())
 if not p.exists() or p.read_text()!=text:p.write_text(text)
