#!/usr/bin/env python3
"""BreadBox title-version contract, portable header generator and packed TMD checks."""
import argparse
from pathlib import Path
import re
import struct
import sys


def parse(version):
    match = re.fullmatch(r'(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)', version)
    if not match:
        raise ValueError('BB_VERSION must be major.minor.patch (nonnegative decimal integers)')
    return tuple(map(int, match.groups()))


def encode(version):
    """BreadBox's CIA title version (16 bits: a 6-bit major field, a 6-bit minor field, a 4-bit micro field).
    major field = BASE + 16*major + minor, minor field = patch, micro = 15 for a release; micro 0..14 of the same
    fields are the private test counters just below that release, so the release installs over them. Every later
    version is larger (the updater installs only a larger number): 0.9.0 = 25615, 0.9.1 = 25631, 1.0.0 = 32783,
    1.0.1 = 32799. BASE puts the first public release, 0.9.0, above every private test CIA installed before it
    (all in 16xxx; the highest 16641). Range: 0.0.0 to 2.15.63."""
    major, minor, patch = parse(version)
    # A carry would alias a different semantic version, even with fixed makerom.
    if minor > 15:
        raise ValueError('minor must be 0..15: minor 16 aliases the next major')
    if BASE + 16 * major + minor > 63:
        raise ValueError(f'{BASE} + 16*major + minor exceeds the 6-bit CIA major field (max 63): 2.15.x is the last')
    if patch > 63:
        raise ValueError('patch must be 0..63: it must fit the 6-bit CIA minor field; bump minor')
    return (BASE + 16 * major + minor) * 1024 + patch * 16 + 15


BASE = 16


def decode(value):
    """Recognize released BreadBox counters; pre-0.9.0 numbers were private builds."""
    value = counter(str(value))
    if value < encode('0.9.0') or value & 15 != 15:
        return None
    field = (value >> 10) - BASE
    return field // 16, field % 16, (value >> 4) & 63


def portable_header():
    return f'''/* Generated by tools/build/title-version.py header; do not edit. */
#ifndef BB_TITLE_VERSION_H
#define BB_TITLE_VERSION_H
#include <stddef.h>
#include <stdio.h>
#define BB_TITLE_VERSION_INVALID 65536u
#define BB_TITLE_VERSION_BASE {BASE}u
#define BB_TITLE_VERSION_FIRST_RELEASE {encode('0.9.0')}u

static inline unsigned bb_title_version_encode(unsigned major, unsigned minor, unsigned patch)
{{
    if (major > 2u || minor > 15u || patch > 63u)
        return BB_TITLE_VERSION_INVALID;
    return (BB_TITLE_VERSION_BASE + 16u * major + minor) * 1024u + patch * 16u + 15u;
}}

/* Returns 0 for private/unrecognized counters; leaves outputs untouched. */
static inline int bb_title_version_decode(unsigned value, unsigned *major, unsigned *minor, unsigned *patch)
{{
    unsigned field;
    if (value > 65535u || value < BB_TITLE_VERSION_FIRST_RELEASE || (value & 15u) != 15u)
        return 0;
    field = (value >> 10) - BB_TITLE_VERSION_BASE;
    *major = field / 16u;
    *minor = field % 16u;
    *patch = (value >> 4) & 63u;
    return 1;
}}

/* What players see: "major.minor.patch" for a release, "test build N" for any
   other counter (micro 0..14 test builds and pre-0.9.0 private builds). */
static inline const char *bb_title_version_text(char *out, size_t size, unsigned value)
{{
    unsigned major, minor, patch;
    if (bb_title_version_decode(value, &major, &minor, &patch))
        snprintf(out, size, "%u.%u.%u", major, minor, patch);
    else
        snprintf(out, size, "test build %u", value);
    return out;
}}
#endif
'''


def encode_psx3d(version):
    """PSX3D's released 0.x mapping (frozen at v0.5.2; another title ID): (major*16+minor)*1024 + patch+3."""
    major, minor, patch = parse(version)
    if minor > 15:
        raise ValueError('minor must be 0..15: minor 16 aliases the next major')
    if patch > 12:
        raise ValueError('patch must be 0..12: patch+3 must fit the 4-bit CIA micro field; bump minor')
    if major * 16 + minor > 63:
        raise ValueError('major*16+minor exceeds the 6-bit CIA major field (max 63)')
    return (major * 16 + minor) * 1024 + patch + 3


def header_version(path):
    matches = re.findall(r'^#define\s+BB_VERSION\s+"([^"\n]+)"', Path(path).read_text(), re.M)
    if len(matches) != 1:
        raise ValueError('expected exactly one BB_VERSION in ' + str(path))
    return matches[0]


def counter(value):
    if not re.fullmatch(r'0|[1-9][0-9]*', value) or not 0 <= int(value) <= 65535:
        raise ValueError('VERSION must be an integer in 0..65535; refusing title-version truncation')
    return int(value)


def cia_version(path, title_id=None):
    # CIA sections are 64-byte aligned. Parse the signed TMD, not makerom stdout.
    align = lambda n: (n + 63) & ~63
    with Path(path).open('rb') as f:
        header = f.read(32)
        if len(header) != 32:
            raise ValueError('truncated CIA header')
        size, kind, version, cert, ticket, tmd_size = struct.unpack_from('<IHHIII', header)
        if size < 32 or size > 0x100000 or kind != 0 or version != 0:
            raise ValueError('unsupported CIA header')
        tmd = align(size) + align(cert) + align(ticket)
        f.seek(tmd)
        sig = f.read(4)
        if len(sig) != 4:
            raise ValueError('missing TMD signature')
        sig_size = {0x10000: 0x240, 0x10001: 0x140, 0x10002: 0x80,
                    0x10003: 0x240, 0x10004: 0x140, 0x10005: 0x80}.get(int.from_bytes(sig, 'big'))
        if sig_size is None or tmd_size < sig_size + 0x9e:
            raise ValueError('invalid/truncated TMD')
        if title_id is not None:
            f.seek(tmd + sig_size + 0x4c)
            actual_id = int.from_bytes(f.read(8), 'big')
            if actual_id != title_id:
                raise ValueError(f'TMD title ID {actual_id:016X} != expected {title_id:016X}')
        f.seek(tmd + sig_size + 0x9c)
        raw = f.read(2)
        if len(raw) != 2:
            raise ValueError('truncated TMD title version')
        return int.from_bytes(raw, 'big')


def main():
    p = argparse.ArgumentParser(description=__doc__)
    sub = p.add_subparsers(dest='command', required=True)
    h = sub.add_parser('header'); h.add_argument('--check', action='store_true')
    e = sub.add_parser('encode'); e.add_argument('header')
    c = sub.add_parser('check'); c.add_argument('header'); c.add_argument('value')
    v = sub.add_parser('verify-cia'); v.add_argument('cia'); v.add_argument('value'); v.add_argument('--title-id', type=lambda s: int(s, 16))
    a = p.parse_args()
    try:
        if a.command == 'header':
            path = Path(__file__).resolve().parents[2] / 'include/breadbox/title_version.h'
            if a.check:
                if path.read_text() != portable_header():
                    raise ValueError('generated include/breadbox/title_version.h is stale; run tools/build/title-version.py header')
            else:
                path.write_text(portable_header())
        elif a.command == 'encode':
            print(encode(header_version(a.header)))
        elif a.command == 'check':
            encode(header_version(a.header))
            counter(a.value)
        else:
            want = counter(a.value)
            actual = cia_version(a.cia, a.title_id)
            if actual != want:
                raise ValueError(f'makerom wrote title version {actual}, requested {want}. '
                                 'The stock makerom drops bits 4..9 (e.g. 5136 becomes 5120); '
                                 'use the pinned tool with tools/build/makerom-version-fix.patch')
            print(f'CIA title version verified: {actual}')
    except (OSError, ValueError, struct.error) as error:
        sys.exit('CIA version error: ' + str(error))

if __name__ == '__main__':
    main()
