#!/usr/bin/env python3
"""systems-table.py OUT.c ID... : write the const system registry for one app.
The app makefile owns the list (apps/<app>.mk SYSTEMS := ps1 gba ...); shared
code only iterates bb_systems[]. Adding a system never edits shared files."""
import re, sys
out, ids = sys.argv[1], sys.argv[2:]
if not ids or len(set(ids)) != len(ids) or any(not re.fullmatch(r'[a-z][a-z0-9]{1,7}', i) for i in ids):
    sys.exit('systems-table.py: need unique lower-case ids, got %r' % ids)
lines = ['/* generated by tools/build/systems-table.py: do not edit */', '#include <string.h>', '#include "bb_system.h"']
lines += ['extern const bb_system_t bb_system_%s;' % i for i in ids]
lines += ['const bb_system_t *const bb_systems[] = { %s };' % ', '.join('&bb_system_%s' % i for i in ids),
          'const unsigned bb_system_count = %d;' % len(ids),
          'const bb_system_t *bb_system_by_id(const char *id)',
          '{', '\tfor (unsigned i = 0; i < bb_system_count; i++)',
          '\t\tif (!strcmp(bb_systems[i]->id, id)) return bb_systems[i];', '\treturn NULL;', '}']
open(out, 'w').write('\n'.join(lines) + '\n')
