#!/usr/bin/env python3
"""Generate direct-call guards for system extension entries, without ABI dispatch.
The manifest contains trusted source expressions (not external inputs). Standard
libretro function tables for the shared host come from retro-bindings.py.
"""
import json,sys
from pathlib import Path
root=Path(__file__).resolve().parents[2]
for manifest in (root/'systems').glob('*/retro-guards.json'):
 lines=['/* Generated by tools/build/retro-legacy-guards.py; do not edit. */']
 for row in json.loads(manifest.read_text()):
  if row['condition']:lines+=['#ifdef '+row['condition']]
  lines+=['#define '+row['name']+'(...) '+row['expression']]
  if row['condition']:lines+=['#endif']
 text='\n'.join(lines)+'\n';out=manifest.with_name('retro_guards.h')
 if '--check' in sys.argv:
  if not out.exists() or out.read_text()!=text:sys.exit('stale generated guards: '+str(out))
 elif not out.exists() or out.read_text()!=text:out.write_text(text)
