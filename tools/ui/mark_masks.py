#!/usr/bin/env python3
"""The selection highlighter's stroke masks (owner 2026-11-12: "a yellow highlighter with some randomness and
scratchiness"; the mockup's "dry" stroke, devtools settings-overhaul NOTES.md section 9).

Writes include/breadbox/ui_mark_masks.h: UI_MARK_VARIANTS strokes of UI_MARK_TEX_W x UI_MARK_TEX_H 8-bit coverage
(an L8 texture, 8 KiB). Each stroke is a 3-slice: the nib's start cap, a streaky middle the draw stretches to the
text, and the dry tail. Deterministic: the same bytes on every run.

    python3 tools/ui/mark_masks.py            # rewrite the header
    python3 tools/ui/mark_masks.py --check    # exit 1 when the committed header differs
    python3 tools/ui/mark_masks.py --ppm F    # a 4x preview of the four strokes
"""
import math, sys
from pathlib import Path

W, H, VARIANTS = 128, 16, 4          # texture cell per stroke
CAP, TAIL = 12, 32                   # slices: [0, CAP) start cap, [W - TAIL, W) dry tail, the middle between
BODY = 11.5                          # the stroke's height inside the cell (the edges wander about a pixel)


def rng(seed):
    s = [seed & 0xffffffff]

    def r():   # mulberry32, as the mockup's renderer
        s[0] = (s[0] + 0x6D2B79F5) & 0xffffffff
        t = s[0]
        t = ((t ^ (t >> 15)) * (1 | t)) & 0xffffffff
        t = (t + (((t ^ (t >> 7)) * (61 | t)) & 0xffffffff)) & 0xffffffff ^ t
        return ((t ^ (t >> 14)) & 0xffffffff) / 4294967296
    return r


def noise1(r, n, step):
    k = [r() * 2 - 1 for _ in range(int(n / step) + 3)]

    def f(x):
        i = int(math.floor(x / step)); t = x / step - i; s = t * t * (3 - 2 * t)
        return k[i] * (1 - s) + k[i + 1] * s
    return f


def stroke(seed):
    r = rng(seed)
    top, bot, slow = noise1(r, W, 5), noise1(r, W, 4), noise1(r, W, 14)
    streak = [1 - .35 * r() for _ in range(H)]                         # bristle lines
    ends = [W - 1 - r() * (TAIL * .7) for _ in range(H)]                # uneven bristle ends inside the tail
    gaps = []                                                          # pen skips, only in the outer thirds
    for _ in range(6):
        outer = (H - BODY) / 2 + (r() * BODY / 3 if r() < .5 else BODY - r() * BODY / 3)
        gaps.append((CAP + r() * (W - CAP - TAIL), 2 + r() * 6, int(outer), .35 + .3 * r()))
    grit = rng(seed * 31 + 7)
    out = [[0] * W for _ in range(H)]
    y0c = (H - BODY) / 2
    for x in range(W):
        tail = max(0.0, (x - (W - TAIL)) / TAIL)                       # 0 before the tail, 1 at its end
        lean = -tail * 1.2                                             # the tail lifts as the pen leaves
        y0 = y0c + lean + top(x) * 1.1
        y1 = y0c + BODY + lean + bot(x) * 1.1
        cap = 3.5                                                      # rounded start: the nib lands as a blob
        inset = (cap - math.sqrt(max(0, cap * cap - (cap - x) ** 2))) * (BODY / 2) / cap * .9 if x < cap else 0
        for j in range(1, H - 1):                                     # the cell's first and last rows stay clear
            yc = j + .5
            cov = min(1, max(0, yc - (y0 + inset))) * min(1, max(0, (y1 - inset) - yc))
            if cov <= 0 or x > ends[j]:
                continue
            k = streak[j] * (1 + .06 * slow(x))
            if x < 2.5:
                k *= 1.12                                              # pressed down at the start
            k *= 1 - tail * .75                                        # the dry tail
            for gx, gw, gj, gk in gaps:
                if gx <= x < gx + gw and abs(j - gj) < 2:
                    k *= gk
            k *= .93 + .14 * grit()                                    # scratch
            out[j][x] = max(0, min(255, round(min(1, cov * k) * 255)))
    return out


def masks():
    return [stroke(1013 + 97 * v) for v in range(VARIANTS)]


def header(m):
    lines = ['/* Generated by tools/ui/mark_masks.py: do not edit. The selection highlighter\'s strokes (ui_mark.h). */',
             '#ifndef UI_MARK_MASKS_H', '#define UI_MARK_MASKS_H',
             f'static const unsigned char ui_mark_masks[{VARIANTS}][{H}][{W}] = {{']
    for v in m:
        lines.append(' {')
        for row in v:
            lines.append('  {' + ','.join(str(b) for b in row) + '},')
        lines.append(' },')
    lines += ['};', '#endif', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    root = Path(__file__).resolve().parents[2]
    dest = root / 'include/breadbox/ui_mark_masks.h'
    text = header(masks())
    if '--check' in sys.argv:
        sys.exit(0 if dest.exists() and dest.read_text() == text else 1)
    if '--ppm' in sys.argv:   # a 4x preview of the four strokes multiplied over the card paper (view with any image tool)
        m, S = masks(), 4
        rows = []
        for v in m:
            for j in range(H):
                line = []
                for x in range(W):
                    k = v[j][x] / 255 * .72
                    line.append(bytes(round(c * (1 - k * (1 - y / 255))) for c, y in zip((240, 226, 196), (255, 214, 30))) * S)
                rows += [b''.join(line)] * S
        Path(sys.argv[sys.argv.index('--ppm') + 1]).write_bytes(b'P6 %d %d 255\n' % (W * S, H * VARIANTS * S) + b''.join(rows))
        sys.exit(0)
    dest.write_text(text)
    print('wrote', dest, VARIANTS * H * W, 'bytes of masks')
